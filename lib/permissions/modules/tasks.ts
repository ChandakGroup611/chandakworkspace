export type TaskRole = keyof typeof TASK_ROLES;
export type TaskPermission = keyof typeof TASK_PERMISSIONS;

export async function canTask(
  userId: string,
  permission: TaskPermission,
  record?: RecordScopeConstraint
): Promise<boolean> {
  return can(userId, TASK_WORKFLOW_MODULE, permission, record);
}
