#!/usr/bin/env node
/**
 * Build-Time Module Manifest Discovery Scanner
 * Governance: Master Architecture Blueprint v2.0
 * 
 * Scans `lib/modules/manifests/*.manifest.ts` and compiles `lib/modules/registry.generated.ts`.
 * A developer drops a new manifest into `lib/modules/manifests/` and it is discovered automatically
 * without modifying any central list or configuration file.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const manifestsDir = path.join(rootDir, 'lib', 'modules', 'manifests');
const targetFile = path.join(rootDir, 'lib', 'modules', 'registry.generated.ts');

if (!fs.existsSync(manifestsDir)) {
  fs.mkdirSync(manifestsDir, { recursive: true });
}

const manifestFiles = fs.readdirSync(manifestsDir)
  .filter(f => f.endsWith('.manifest.ts'))
  .sort();

console.log(`[Module Discovery] Scanning ${manifestsDir}...`);
console.log(`[Module Discovery] Found ${manifestFiles.length} module manifest(s): ${manifestFiles.join(', ') || 'none'}`);

// Generate imports and registry entries
const imports = [];
const entries = [];

manifestFiles.forEach((file, idx) => {
  const baseName = file.replace('.manifest.ts', '');
  const varName = `manifest_${baseName.replace(/[^a-zA-Z0-9_]/g, '_')}`;
  imports.push(`import { default as ${varName} } from "./manifests/${file.replace('.ts', '')}";`);
  entries.push(`  [${varName}.code]: ${varName},`);
});

const generatedContent = `/**
 * AUTO-GENERATED BY scripts/generate-module-registry.mjs
 * DO NOT EDIT MANUALLY - DROPPING A *.manifest.ts FILE IN lib/modules/manifests/ AUTO-DISCOVERS IT
 */

import type { ModuleManifest } from "./types";

${imports.join('\n')}

export const MODULE_REGISTRY: Record<string, ModuleManifest> = {
${entries.join('\n')}
};

export function getRegisteredModules(): ModuleManifest[] {
  return Object.values(MODULE_REGISTRY);
}

export function getActiveModules(): ModuleManifest[] {
  return Object.values(MODULE_REGISTRY).filter(m => m.status === "ACTIVE");
}

export function getModuleManifest(code: string): ModuleManifest | null {
  return MODULE_REGISTRY[code] || null;
}
`;

fs.writeFileSync(targetFile, generatedContent, 'utf8');
console.log(`[Module Discovery] Successfully compiled registry to ${targetFile}`);
